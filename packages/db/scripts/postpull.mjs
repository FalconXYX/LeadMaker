// Runs after `prisma db pull`. Prisma reads a partial unique index (UNIQUE ... WHERE) as plain
// uniqueness, so findUnique could return closed allocations, finished jobs or superseded overrides,
// and companies.lead_allocations would become one-to-one although it is a history. Demote every
// partial unique to a partial @@index, turn the back-relations it made one-to-one into lists, and
// hide the PostGIS / dbmate bookkeeping tables from the client.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const HEADER = '// Generated by `npm run db:pull` (prisma db pull + scripts/postpull.mjs) from the dbmate-migrated\n// database. Change db/migrations, then re-pull; never edit models by hand.\n';
const IGNORED_MODELS = ['schema_migrations', 'spatial_ref_sys'];
const FIELD_UNIQUE = /\s*@unique\(((?:map: "[^"]+", )?where: raw\("(?:[^"\\]|\\.)*"\))\)/;
const BLOCK_UNIQUE = /@@unique\((\[[^\]]+\], (?:map: "[^"]+", )?where: raw\("(?:[^"\\]|\\.)*"\))\)/g;

export function fixSchema(src) {
  const models = new Map();
  for (const m of src.matchAll(/^model (\w+) \{\n([\s\S]*?)^\}/gm)) models.set(m[1], m[2]);

  const demoted = [];
  for (const [name, body] of models) {
    const lines = body.split('\n');
    const extra = [];
    for (let i = 0; i < lines.length; i++) {
      const hit = lines[i].match(FIELD_UNIQUE);
      if (!hit) continue;
      const field = lines[i].trim().split(/\s+/)[0];
      lines[i] = lines[i].replace(FIELD_UNIQUE, '');
      extra.push(`  @@index([${field}], ${hit[1]})`);
      demoted.push({ model: name, field });
    }
    let next = lines.join('\n').replace(BLOCK_UNIQUE, '@@index($1)');
    if (extra.length) next = next.replace(/\n*$/, `\n${extra.join('\n')}\n`);
    if (IGNORED_MODELS.includes(name) && !next.includes('@@ignore')) next = next.replace(/\n*$/, '\n  @@ignore\n');
    models.set(name, next);
  }

  for (const { model, field } of demoted) {
    for (const line of models.get(model).split('\n')) {
      const rel = line.match(/^\s*\w+\s+(\w+)\??\s+@relation\((?:"([^"]+)", )?.*fields: \[(\w+)\]/);
      if (!rel || rel[3] !== field) continue;
      const [, target, relationName] = rel;
      const back = new RegExp(
        `^(\\s*\\w+\\s+)${model}\\?(\\s*${relationName ? `@relation\\("${relationName}"\\)` : ''}\\s*)$`,
        'm',
      );
      models.set(target, models.get(target).replace(back, `$1${model}[]$2`));
    }
  }

  const out = src.replace(/^model (\w+) \{\n([\s\S]*?)^\}/gm, (_, name) => `model ${name} {\n${models.get(name)}}`);
  return out.startsWith(HEADER) ? out : HEADER + out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const path = new URL('../prisma/schema.prisma', import.meta.url);
  writeFileSync(path, fixSchema(readFileSync(path, 'utf8')));
}
