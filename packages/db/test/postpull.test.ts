import { describe, expect, it } from 'vitest';
// @ts-expect-error plain .mjs script without types
import { fixSchema } from '../scripts/postpull.mjs';

const pulled = `generator client {
  provider = "prisma-client"
}

model companies {
  id               String             @id @db.Uuid
  lead_allocations lead_allocations?
  owner            users?             @relation("companies_ownerTousers")
}

model lead_allocations {
  id         String    @id @db.Uuid
  company_id String    @unique(map: "lead_allocations_one_open", where: raw("(ended_at IS NULL)")) @db.Uuid
  companies  companies @relation(fields: [company_id], references: [id], onDelete: Cascade, onUpdate: NoAction)

  @@index([company_id, allocated_at(sort: Desc)], map: "lead_allocations_history_idx")
}

model users {
  id        String     @id @db.Uuid
  owner_of  String     @unique(map: "users_owner_of_open", where: raw("(active)")) @db.Uuid
  companies companies  @relation("companies_ownerTousers", fields: [owner_of], references: [id])
}

model field_overrides {
  id String @id
  @@unique([company_id, contact_id, field], map: "field_overrides_one_active", where: raw("(superseded_at IS NULL)"))
  @@unique([id, field])
}

model jobs {
  dedupe_key String? @unique(map: "jobs_open_dedupe_key", where: raw("((status)::text = ANY ((ARRAY['queued'::character varying])::text[]))")) @db.VarChar(200)
}

model spatial_ref_sys {
  srid Int @id
}

model schema_migrations {
  version String @id @db.VarChar
}
`;

describe('fixSchema', () => {
  const fixed: string = fixSchema(pulled);

  it('demotes field-level partial uniques to partial indexes', () => {
    expect(fixed).toContain('company_id String @db.Uuid');
    expect(fixed).toContain('@@index([company_id], map: "lead_allocations_one_open", where: raw("(ended_at IS NULL)"))');
    expect(fixed).toContain('dedupe_key String? @db.VarChar(200)');
    expect(fixed).toMatch(/@@index\(\[dedupe_key\], map: "jobs_open_dedupe_key", where: raw\(.*ARRAY\['queued'.*\)\)/);
    expect(fixed).not.toMatch(/@unique\([^)]*where:/);
  });

  it('demotes block-level partial uniques and keeps full uniques', () => {
    expect(fixed).toContain('@@index([company_id, contact_id, field], map: "field_overrides_one_active"');
    expect(fixed).toContain('@@unique([id, field])');
  });

  it('turns back-relations made one-to-one by a partial unique into lists', () => {
    expect(fixed).toContain('lead_allocations lead_allocations[]');
    expect(fixed).toContain('owner            users[]             @relation("companies_ownerTousers")');
  });

  it('hides the PostGIS and dbmate tables from the client', () => {
    expect(fixed).toMatch(/model spatial_ref_sys \{[^}]*@@ignore\n\}/);
    expect(fixed).toMatch(/model schema_migrations \{[^}]*@@ignore\n\}/);
  });

  it('is idempotent and adds the generated-file header once', () => {
    expect(fixSchema(fixed)).toBe(fixed);
    expect(fixed.startsWith('// Generated by `npm run db:pull`')).toBe(true);
  });
});
