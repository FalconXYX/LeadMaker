-- Ingestion tables of the Python pipeline, keyed by companies.id. Integer ids are BY DEFAULT identities
-- so the Section 1 importer can keep its run ids (then setval the sequences).
CREATE TABLE scrape_runs (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind VARCHAR(32) NOT NULL,                               -- gaf_ingest | enrich | tag | signals | ...
    status VARCHAR(16) NOT NULL CHECK (status IN ('running', 'succeeded', 'partial', 'failed')),
    params JSONB NOT NULL DEFAULT '{}',
    stats JSONB NOT NULL DEFAULT '{}',
    error TEXT,
    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    finished_at TIMESTAMPTZ
);

-- Distance is query-relative, so it lives here (one row per company per run), not on the company
CREATE TABLE search_hits (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id INT NOT NULL REFERENCES scrape_runs(id) ON DELETE CASCADE,
    company_id UUID NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
    postal_code VARCHAR(16) NOT NULL,
    radius_miles DOUBLE PRECISION NOT NULL,
    distance_miles DOUBLE PRECISION,
    rank INT NOT NULL,
    gaf_recommended BOOLEAN NOT NULL DEFAULT FALSE,
    gaf_recommended_rank INT,
    seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (run_id, company_id)
);
CREATE INDEX search_hits_company_idx ON search_hits (company_id);
CREATE INDEX search_hits_area_idx ON search_hits (postal_code, radius_miles, run_id);

CREATE TABLE reviews (
    id VARCHAR(64) PRIMARY KEY,                              -- content hash -> idempotent re-inserts
    company_id UUID NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
    author VARCHAR(255),
    rating DOUBLE PRECISION,
    text TEXT,
    published_at TIMESTAMPTZ,
    source VARCHAR(64),
    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX reviews_company_idx ON reviews (company_id);

-- One row per company x secondary source: raw result, match confidence and provenance
CREATE TABLE enrichments (
    company_id UUID NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
    source VARCHAR(32) NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('ok', 'no_match', 'skipped', 'error')),
    match_confidence DOUBLE PRECISION NOT NULL DEFAULT 0,
    data JSONB NOT NULL DEFAULT '{}',
    website TEXT,
    source_urls JSONB NOT NULL DEFAULT '[]',
    error TEXT,
    run_id INT REFERENCES scrape_runs(id) ON DELETE SET NULL,
    fetched_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    input_hash VARCHAR(64),                                  -- inputs the enricher saw; a change forces a re-run inside the TTL
    PRIMARY KEY (company_id, source)
);
CREATE INDEX enrichments_source_status_idx ON enrichments (source, status);

-- Append-only pipeline change log with field-level diffs. run_id and company_id are not FKs:
-- the log must outlive pruned runs and deleted companies.
CREATE TABLE audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id INT,
    entity_type VARCHAR(32) NOT NULL,                        -- company | profile | enrichment | contact | tags | area | accounts
    entity_id VARCHAR(160) NOT NULL,                         -- company id, or company_id:source
    company_id UUID,
    action VARCHAR(16) NOT NULL,                             -- created | updated | removed | delisted
    changes JSONB NOT NULL DEFAULT '{}',                     -- {field: [old, new]}
    actor_type VARCHAR(20) NOT NULL DEFAULT 'pipeline' CHECK (actor_type IN ('user', 'pipeline', 'system')),
    actor_id UUID,
    at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX audit_events_company_at_idx ON audit_events (company_id, at);
CREATE INDEX audit_events_run_idx ON audit_events (run_id);
CREATE INDEX audit_events_at_idx ON audit_events (at);

CREATE TABLE schedules (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(128) NOT NULL UNIQUE,
    kind VARCHAR(32) NOT NULL,
    params JSONB NOT NULL DEFAULT '{}',
    every_hours DOUBLE PRECISION NOT NULL CHECK (every_hours > 0),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    next_run_at TIMESTAMPTZ NOT NULL,
    last_enqueued_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- DB-backed job queue: workers claim with FOR UPDATE SKIP LOCKED
CREATE TABLE jobs (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind VARCHAR(32) NOT NULL,                               -- scrape | enrich | tag | pipeline | signals
    params JSONB NOT NULL DEFAULT '{}',
    dedupe_key VARCHAR(200),
    status VARCHAR(16) NOT NULL DEFAULT 'queued' CHECK (status IN ('queued', 'running', 'succeeded', 'failed', 'dead')),
    priority INT NOT NULL DEFAULT 100,                       -- lower runs first
    attempts INT NOT NULL DEFAULT 0,
    max_attempts INT NOT NULL DEFAULT 3,
    run_after TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    locked_by VARCHAR(64),
    locked_at TIMESTAMPTZ,
    result JSONB,
    error TEXT,
    schedule_id INT REFERENCES schedules(id) ON DELETE SET NULL,
    requested_by UUID REFERENCES users(id),                  -- user for on-demand jobs; NULL for schedules/CLI
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    finished_at TIMESTAMPTZ
);
CREATE INDEX jobs_claim_idx ON jobs (status, run_after, priority);
CREATE UNIQUE INDEX jobs_open_dedupe_key ON jobs (dedupe_key) WHERE status IN ('queued', 'running');  -- duplicates merge
CREATE INDEX jobs_requested_by_idx ON jobs (requested_by, created_at) WHERE requested_by IS NOT NULL;  -- per-user hourly limit

-- The distributor's customer list (CRM import); matching it to companies sets companies.account_status
CREATE TABLE accounts (
    account_id VARCHAR(64) PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    phone VARCHAR(64),
    postal_code VARCHAR(16),
    city VARCHAR(128),
    state VARCHAR(8),
    status VARCHAR(32),                                      -- active | inactive | prospect | do_not_contact
    owner_rep VARCHAR(128),
    annual_spend DOUBLE PRECISION,
    last_order_at TIMESTAMPTZ,
    extra JSONB NOT NULL DEFAULT '{}',
    company_id UUID REFERENCES companies(id) ON DELETE SET NULL,
    match_confidence DOUBLE PRECISION,
    match_method VARCHAR(32),
    imported_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX accounts_company_idx ON accounts (company_id);

